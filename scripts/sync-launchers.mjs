#!/usr/bin/env node
// WINDOWS CANNOT EXECUTE A SHEBANG. Generate a .cmd twin for every launcher.
//
//   node scripts/sync-launchers.mjs           # write any missing or stale twins
//   node scripts/sync-launchers.mjs --check   # exit 1 if any is missing or stale
//
// The first Windows contributor found this the expensive way: `bin/harness-*` are extensionless
// `#!/bin/sh` files, Windows ignores shebangs, so every command was unrunnable and every test that
// shelled out to one asserted against empty output. The harness installed and could not verify.
//
// GENERATED, NOT HAND-WRITTEN, and that is the whole design. Twenty-three near-identical files
// maintained by hand is twenty-three chances to add a launcher and forget its twin — and the twin
// that is missing is invisible until somebody on Windows runs exactly that command. The module path
// is DERIVED from the shell launcher's own text, so the two cannot disagree about what they run.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..");
const PLUGINS = join(REPO, "plugins");

/** Every shell launcher, paired with the module its own body names. */
export function launchers(root = PLUGINS) {
  const out = [];
  for (const plugin of readdirSync(root)) {
    const bin = join(root, plugin, "bin");
    let names = [];
    try {
      names = readdirSync(bin);
    } catch {
      continue; // a plugin without launchers is fine
    }
    for (const name of names) {
      if (name.endsWith(".cmd")) continue;
      const body = readFileSync(join(bin, name), "utf8");
      // A launcher with no module is a REAL SHELL PROGRAM, not a wrapper — `harness-ship`
      // orchestrates git and gh in bash. It cannot be twinned mechanically, and leaving it with no
      // twin at all is the dead end this whole exercise is against: the command silently does not
      // exist, and the user concludes they typed it wrong. It gets an explaining twin instead.
      out.push({ plugin, name, module: body.match(/lib\/([\w.-]+\.mjs)/)?.[1] ?? null, path: join(bin, name) });
    }
  }
  return out.sort((a, b) => a.name.localeCompare(b.name));
}

/**
 * The .cmd body. Mirrors the shell launcher exactly: prefer CLAUDE_PLUGIN_ROOT when Claude Code sets
 * it, fall back to resolving its own directory so a direct invocation from a checkout still works.
 *
 * `%*` rather than %1..%9 — arguments past the ninth would be silently dropped otherwise, and a
 * scanner invoked with a long file list is exactly where that would bite.
 */
export function cmdBody(module, name = "this command") {
  // No module means a shell program. Say so, say why, and say what to do — a command that fails
  // without naming its own replacement is the failure mode, not the absence of the command.
  if (!module) {
    return [
      "@echo off",
      ":: GENERATED by scripts/sync-launchers.mjs — edit that, not this.",
      `echo(${name} is a POSIX shell program and cannot run on Windows.`,
      "echo(",
      "echo(It orchestrates git and gh directly rather than wrapping a Node module, so there is",
      "echo(nothing here to hand to node. Run it from WSL, macOS or Linux.",
      "echo(",
      "echo(Everything else in the harness works here - only this one command does not.",
      "exit /b 1",
      "",
    ].join("\r\n");
  }
  return [
    "@echo off",
    ":: GENERATED by scripts/sync-launchers.mjs — edit that, not this.",
    ":: Windows ignores a shebang, so the sibling shell launcher is unrunnable here.",
    'if defined CLAUDE_PLUGIN_ROOT if exist "%CLAUDE_PLUGIN_ROOT%\\lib\\' + module + '" (',
    '  node "%CLAUDE_PLUGIN_ROOT%\\lib\\' + module + '" %*',
    "  exit /b %errorlevel%",
    ")",
    'node "%~dp0..\\lib\\' + module + '" %*',
    "exit /b %errorlevel%",
    "",
  ].join("\r\n"); //  CRLF: a .cmd with bare LF misparses on some Windows shells
}

const check = process.argv.includes("--check");
const found = launchers();
const stale = [];

for (const l of found) {
  const twin = `${l.path}.cmd`;
  const want = cmdBody(l.module, l.name);
  let have = null;
  try {
    have = readFileSync(twin, "utf8");
  } catch {
    /* missing counts as stale */
  }
  // Compare content, not line endings. `.gitattributes` stores these LF and checks them out CRLF,
  // so a byte comparison reports every twin stale on whichever platform is not the one that wrote
  // them — a check that cries wolf gets run with --no-verify within a week.
  if (have !== null && have.replace(/\r\n/g, "\n") === want.replace(/\r\n/g, "\n")) continue;
  stale.push(`${l.plugin}/bin/${l.name}.cmd`);
  if (!check) writeFileSync(twin, want);
}

if (check && stale.length) {
  console.error(`✗ ${stale.length} launcher twin(s) missing or stale:\n`);
  for (const s of stale) console.error(`    ${s}`);
  console.error("\n  Run `node scripts/sync-launchers.mjs`. A launcher without its twin is a command");
  console.error("  that does not exist on Windows, and nothing notices until somebody there runs it.");
  process.exit(1);
}

console.log(
  check
    ? `✓ all ${found.length} launchers have a current .cmd twin`
    : stale.length
      ? `✓ wrote ${stale.length} twin(s); ${found.length} launchers covered`
      : `✓ nothing to do — all ${found.length} twins current`,
);
